function anel(pontos) {
  return `${pontos
    .map(([lng, lat], i) => {
      const x = (lng + 180).toFixed(2)
      const y = (90 - lat).toFixed(2)
      return `${i ? 'L' : 'M'}${x} ${y}`
    })
    .join(' ')} Z`
}

